CREATE TABLE IF NOT EXISTS ranked_profiles (
  id TEXT PRIMARY KEY, name TEXT NOT NULL, rating INTEGER NOT NULL DEFAULT 1000,
  wins INTEGER NOT NULL DEFAULT 0, losses INTEGER NOT NULL DEFAULT 0,
  draws INTEGER NOT NULL DEFAULT 0, games INTEGER NOT NULL DEFAULT 0, verified INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS ranked_results (
  id TEXT PRIMARY KEY, completed_at INTEGER NOT NULL, result TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ranked_rating ON ranked_profiles(rating DESC, wins DESC);
